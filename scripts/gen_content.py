def gen_daily(anchors, reviews):
    """生成每日汇总日报 data/daily.json(基于真实抓取数据滚动汇总)"""
    live = [a for a in anchors if a.get("isLive")]
    fans_sum = sum(a.get("followers") or 0 for a in anchors)
    delta_sum = sum(a.get("followerDelta") or 0 for a in anchors)
    rev_sum = sum(a.get("revenue30d") or 0 for a in anchors)
    head = sum(1 for a in anchors if a.get("tier") == "头部")
    waist = sum(1 for a in anchors if a.get("tier") == "腰部")
    n = len(reviews) or 1
    avg = lambda k: sum(r.get(k) or 0 for r in reviews) / n  # noqa: E731
    top_live = sorted(live, key=lambda x: -x.get("popularity", 0))[:3]
    top_gain = sorted(anchors, key=lambda x: -(x.get("followerDelta") or 0))[:3]

    summary = ("今日库内主播 %d 位,当前开播 %d 场(开播率 %d%%),粉丝总量 %s,涨粉 %s;"
               "人气前三:%s;涨粉前三:%s。复盘口径:留存率 %.1f%% / 3分钟停留 %.1f%% / 开播率 %.1f%%。"
               % (len(anchors), len(live), round(len(live) / max(len(anchors), 1) * 100),
                  fmt_w(fans_sum), ("+" if delta_sum >= 0 else "") + fmt_w(delta_sum),
                  ("、".join(a["name"] for a in top_live) if top_live else "无"),
                  ("、".join(a["name"] for a in top_gain) if top_gain else "无"),
                  avg("retention") * 100, avg("stay3m") * 100, avg("openRate") * 100))
    highlights = [
        "库内主播 %d 位(头部 %d / 腰部 %d / 潜力 %d)" % (len(anchors), head, waist, len(anchors) - head - waist),
        "当前开播 %d 场,30 天内粉丝快照每日留存,涨粉可跨期对比" % len(live),
        "预估 30 天营收合计 ¥%s(估算口径)" % fmt_w(rev_sum),
    ]
    return {
        "date": TODAY,
        "updatedAt": NOW.strftime("%Y-%m-%dT%H:%M:%S") + TZ,
        "source": "scripts/gen_content.py 基于当日全量抓取数据生成",
        "totalAnchors": len(anchors),
        "liveCount": len(live),
        "totalFollowers": fans_sum,
        "followerDelta": delta_sum,
        "estRevenue30d": rev_sum,
        "reviewCount": len(reviews),
        "stats": {"head": head, "waist": waist, "potential": len(anchors) - head - waist},
        "reviewAvg": {"retention": round(avg("retention"), 4), "stay3m": round(avg("stay3m"), 4),
                      "openRate": round(avg("openRate"), 4), "payRate": round(avg("payRate"), 4)},
        "topLive": [{"name": a["name"], "popularity": a.get("popularity", 0), "uid": a["uid"]} for a in top_live],
        "topGain": [{"name": a["name"], "delta": a.get("followerDelta", 0), "uid": a["uid"]} for a in top_gain],
        # 兼容旧日报页字段
        "totalLiveCount": len(live),
        "totalNewFollowers": delta_sum,
        "avgInteraction": round(avg("retention"), 3),
        "totalRevenue": rev_sum,
        "insights": {"discovered": len(live), "summary": summary, "highlights": highlights},
    }


def archive_daily(data):
    """把当日日报归档到 data/daily_history/{date}.json 并重建 index.json"""
    hist_dir = os.path.join(DATA_DIR, "daily_history")
    os.makedirs(hist_dir, exist_ok=True)
    d = data.get("date") or TODAY
    with open(os.path.join(hist_dir, d + ".json"), "w", encoding="utf-8") as fp:
        json.dump(data, fp, ensure_ascii=False, separators=(",", ":"))
    dates = sorted(f[:-5] for f in os.listdir(hist_dir) if f.endswith(".json") and f != "index.json")
    with open(os.path.join(hist_dir, "index.json"), "w", encoding="utf-8") as fp:
        json.dump({"updatedAt": NOW.strftime("%Y-%m-%dT%H:%M:%S") + TZ, "dates": dates[::-1]}, fp, ensure_ascii=False)
    print("已归档日报 %s(历史共 %d 天)" % (d, len(dates)))


