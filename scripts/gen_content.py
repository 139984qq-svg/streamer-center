        for kw in kws:
            for a in active:
                if kw in (a.get("title") or "") and a["url"] not in used:
                    used.add(a["url"])
                    return a
        for kw in kws:
            for a in active:
                if kw in (a.get("title") or ""):
                    used.add(a["url"])
                    return a
        for a in pool:
            if a["url"] not in used:
                used.add(a["url"])
                return a
