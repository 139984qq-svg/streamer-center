def load_activities():
    """读取 data/activities.json(B站官方活动列表页实抓的活动落地页表)"""
    path = os.path.join(DATA_DIR, "activities.json")
    try:
        with open(path, "r", encoding="utf-8") as fp:
            j = json.load(fp)
        return j.get("activities") or []
    except Exception:
        return []


