def days_to(dates):
    """从档期字符串解析首个日期,返回距今天数(无法解析返回 None)"""
    import re
    m = re.search(r"(\d{4})-(\d{2})-(\d{2})", dates or "")
    if not m:
        return None
    try:
        target = datetime.strptime(m.group(0), "%Y-%m-%d")
        return (target.date() - NOW.date()).days
    except Exception:
        return None


